let currentLang = DEFAULT_LANG;

function initLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === 'ru' || stored === 'en') currentLang = stored;
  } catch (_) { /* localStorage бывает недоступен */ }
  document.documentElement.setAttribute('lang', currentLang);
}

function getLang() {
  return currentLang;
}

function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'ru';
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch (_) { /* localStorage бывает недоступен */ }
  location.reload();
}

function t(key, params) {
  const dict = MESSAGES[currentLang] || MESSAGES[DEFAULT_LANG];
  let text = dict[key];
  if (text === undefined) text = (MESSAGES[DEFAULT_LANG][key] || key);
  if (params) {
    Object.keys(params).forEach(function (k) {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(params[k]));
    });
  }
  return text;
}

function formatWait(secs) {
  if (secs < 60) return t('auth.waitSec', {n: secs});
  const mins = Math.ceil(secs / 60);
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  const parts = [];
  if (h) parts.push(t('auth.waitHour', {n: h}));
  if (m) parts.push(t('auth.waitMin', {n: m}));
  return parts.join(' ');
}

function localeTag() {
  return currentLang === 'en' ? 'en-US' : 'ru-RU';
}

function timezoneCityName(id) {
  if (currentLang === 'ru' && TZ_CITIES_RU[id]) return TZ_CITIES_RU[id];
  const parts = id.split('/');
  return parts[parts.length - 1].replace(/_/g, ' ');
}

function formatTimezoneLabel(entry) {
  // без "UTC" в каждой строке: город на смещение один, и читается это как выбор пояса
  const offset = entry.offset || '+00:00';
  return timezoneCityName(entry.id) + ' (' + offset + ')';
}

function timezoneOffset(id) {
  const parts = new Intl.DateTimeFormat('en-US', { timeZone: id, timeZoneName: 'longOffset' }).formatToParts(new Date());
  const name = (parts.find(function (p) { return p.type === 'timeZoneName'; }) || {}).value || 'GMT';
  // longOffset дает "GMT+03:00", а для UTC просто "GMT"
  return name === 'GMT' ? '+00:00' : name.slice(3);
}

function timezoneOffsetMinutes(offset) {
  const m = /^([+-])(\d{2}):(\d{2})$/.exec(offset || '');
  if (!m) return 0;
  return (m[1] === '-' ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3]));
}

function timezoneEntries(preferredId) {
  // на смещение один город, иначе в списке десятки "+03:00". Сохраненная зона всегда остается
  // в списке, иначе первое сохранение формы сбросит ее на серверную. UTC прячем, если он не выбран
  const byOffset = new Map();
  Object.keys(TZ_CITIES_RU).forEach(function (id) {
    if (id === 'UTC' && id !== preferredId) return;
    const offset = timezoneOffset(id);
    if (!byOffset.has(offset) || id === preferredId) byOffset.set(offset, id);
  });
  const list = [];
  byOffset.forEach(function (id, offset) {
    list.push({ id: id, offset: offset });
  });
  return list.sort(function (a, b) {
    return timezoneOffsetMinutes(b.offset) - timezoneOffsetMinutes(a.offset);
  });
}

function applyStaticI18n() {
  document.title = t('app.title');
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
}

